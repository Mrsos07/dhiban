class ConversationState(Enum):
    """حالة المحادثة — يحدد سلوك الوكيل"""
    CHAT = "chat"              # سولفة عادية — لا يحتاج بحث
    NEEDS_CLARIFICATION = "needs_clarification"  # يحتاج سؤال توضيحي قبل البحث
