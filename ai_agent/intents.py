def extract_entities(text: str) -> Dict:
    """استخراج الكيانات من النص بشكل ذكي - يفهم المشاكل الوصفية"""
    entities = {
        'category': None,
        'search_query': None,
        'keywords': [],
        'use_google': False,
        'is_problem': False  # هل هو وصف مشكلة
    }
    
    text_lower = text.strip()
    
    # التحقق إذا كان طلب إصلاح/خدمة
    for indicator in SERVICE_INDICATORS:
        if indicator in text_lower:
            entities['is_problem'] = True
            break
    
    # البحث عن التصنيف - نبحث عن أكثر الكلمات تطابقاً
    best_category = None
    best_match_count = 0
    matched_keywords = []
    
    for category, keywords in CATEGORY_KEYWORDS.items():
        match_count = 0
        current_matches = []
        for keyword in keywords:
            if keyword in text_lower:
                match_count += 1
                current_matches.append(keyword)
        
        # اختيار التصنيف الأكثر تطابقاً
        if match_count > best_match_count:
            best_match_count = match_count
            best_category = category
            matched_keywords = current_matches
    
    if best_category:
        entities['category'] = best_category
        entities['keywords'] = matched_keywords
        # استخدام اسم التصنيف كـ search_query
        entities['search_query'] = best_category
        # تحديد إذا كان يحتاج Google Maps
        if best_category in GOOGLE_CATEGORIES:
            entities['use_google'] = True
    
    # إذا لم نجد تصنيف، نستخدم النص كاملاً كـ query
    if not entities['search_query']:
        # إزالة كلمات البحث الشائعة
        clean_text = text_lower
        for word in ['ابي', 'أبي', 'ابغى', 'وين', 'اقرب', 'افضل', 'أفضل', 'احسن', 'هل', 'فيه', 'احد']:
            clean_text = clean_text.replace(word, '').strip()
        entities['search_query'] = clean_text if clean_text else text_lower
    
    return entities


def detect_intent(text: str) -> Intent:
    """
    اكتشاف نية المستخدم من النص - يفهم المشاكل الوصفية
    مثال: "ماصورة المويه تقطر" -> يفهم أنه يحتاج سباك
    """
    text_clean = text.strip()
    text_lower = text_clean.lower()
    
    # استخراج الكيانات أولاً (مهم لفهم المشاكل)
    entities = extract_entities(text_clean)
    
    best_intent = IntentType.UNKNOWN
    best_score = 0
    best_priority = 0
    
    # إذا وجدنا تصنيف من المشاكل الوصفية، نعتبره طلب خدمة
    if entities['category'] and entities.get('is_problem'):
        # هذا وصف مشكلة، نحتاج خدمة
        if entities['use_google']:
            best_intent = IntentType.SEARCH_PLACE
        else:
            best_intent = IntentType.SEARCH_SERVICE
        best_score = len(entities['keywords'])
        confidence = 0.9  # ثقة عالية لأننا فهمنا المشكلة
    else:
        # فحص كل نوع نية
        for intent_type, config in INTENT_PATTERNS.items():
            score = 0
            
            # فحص الكلمات المفتاحية
            for keyword in config['keywords']:
                if keyword in text_lower:
                    score += 1
            
            # فحص الأنماط (regex)
            for pattern in config.get('patterns', []):
                if re.search(pattern, text_lower):
                    score += 2  # الأنماط لها وزن أعلى
            
            # اختيار النية الأفضل (بناءً على Score ثم Priority)
            if score > best_score or (score == best_score and config['priority'] > best_priority):
                best_score = score
                best_intent = intent_type
                best_priority = config['priority']
        
        # تحديد الثقة
        if best_score == 0:
            # إذا لم نجد شيء، نفترض بحث عام
            if entities['category']:
                best_intent = IntentType.SEARCH_FOOD if entities['use_google'] else IntentType.SEARCH_SERVICE
                confidence = 0.7
            else:
                confidence = 0.3
        else:
            confidence = min(best_score / 4, 1.0)
    
    # رفع الثقة إذا وجدنا تصنيف
    if entities['category']:
        confidence = min(confidence + 0.2, 1.0)
    
    # تحديد استخدام Google
    use_google = entities.get('use_google', False) or best_intent in [
        IntentType.SEARCH_FOOD, 
        IntentType.SEARCH_PLACE,
        IntentType.GET_DIRECTIONS
    ]
    
    # النوايا السياحية تستخدم Google Maps دائماً
    if best_intent in TOURISM_INTENTS:
        use_google = True
    
    # تحديد إذا تحتاج سؤال متابعة
    follow_up = best_intent in NEEDS_FOLLOWUP_INTENTS
    
    # تحديد نوع الخطة
    plan_type_map = {
        IntentType.DAILY_PLAN: 'daily',
        IntentType.WEEKEND_PLAN: 'weekend',
        IntentType.EVENING_PLAN: 'evening',
        IntentType.MORNING_PLAN: 'morning',
        IntentType.OUTING_FOOD: 'food_outing',
        IntentType.OUTING_WALK: 'walk_outing',
        IntentType.OUTING_COFFEE: 'coffee_outing',
        IntentType.OUTING_FAMILY: 'family_outing',
        IntentType.OUTING_FRIENDS: 'friends_outing',
        IntentType.OUTING_ROMANTIC: 'romantic_outing',
        IntentType.OUTING_KIDS: 'kids_outing',
        IntentType.ACTIVITY_SUGGESTION: 'suggestion',
        IntentType.MOOD_BASED: 'mood',
        IntentType.EXPLORE: 'explore',
    }
    p_type = plan_type_map.get(best_intent, '')
    
    return Intent(
        type=best_intent,
        confidence=confidence,
        entities=entities,
        original_text=text_clean,
        use_google=use_google,
        needs_followup=follow_up,
        plan_type=p_type
    )


